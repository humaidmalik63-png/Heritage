"""Build the recognition gallery's image assets from the project's REAL photographs.

Reads ONLY from `data/raw/` and writes ONLY into `frontend_new/assets/`.
No source photograph is modified, moved or renamed.

Run from the project root with the Python that has Pillow:

    C:/Users/humai/AppData/Local/Python/bin/python frontend_new/scripts/prepare_gallery.py

Why this exists
---------------
The gallery needs real photographs of the monuments the API can identify.
The only genuine photographs in the repository are the indexed source images
under `data/raw/<site>/` (the very images the FAISS index was built from) and
`data/raw/global/<site_id>/`.  The originals are 60 KB - 30 MB; serving them
straight to a browser would be unusable.  So each one is transcoded here into
a hero-sized and a thumbnail-sized WebP, and a manifest is written listing
exactly the files that exist.

Nothing is invented: the manifest is derived from the directory listing and
contains one entry per real file.  A site with three photographs gets three
gallery images, never five.
"""

from __future__ import annotations

import json
import os

from PIL import Image, ImageOps

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
RAW = os.path.join(ROOT, "data", "raw")
FRONTEND = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
ASSETS = os.path.join(FRONTEND, "assets")
GALLERY_DIR = os.path.join(ASSETS, "images", "gallery")
MANIFEST = os.path.join(ASSETS, "data", "gallery.json")

# The brief asks for up to five images.  This project holds at most three
# photographs per monument, so the cap is a ceiling, not a target — the
# manifest records however many real files were found.
MAX_PER_SITE = 5

# (suffix, longest edge, quality)
HERO = ("lg", 1400, 80)
THUMB = ("sm", 520, 78)


def _write_variant(im: Image.Image, dst_dir: str, stem: str, spec) -> str:
    suffix, max_edge, quality = spec
    out = im.copy()
    out.thumbnail((max_edge, max_edge), Image.LANCZOS)
    dst = os.path.join(dst_dir, f"{stem}-{suffix}.webp")
    out.save(dst, "WEBP", quality=quality, method=6)
    # relative to the frontend root, so the page can request it directly
    return os.path.relpath(dst, FRONTEND).replace("\\", "/")


def _collect(site_dir: str, site_id: str, sites: dict) -> int:
    """Transcode every real photograph in `site_dir`; append to `sites`."""
    if not os.path.isdir(site_dir):
        return 0

    names = sorted(
        n for n in os.listdir(site_dir)
        if n.lower().endswith((".jpg", ".jpeg", ".png", ".webp"))
    )[:MAX_PER_SITE]
    if not names:
        return 0

    dst_dir = os.path.join(GALLERY_DIR, site_id)
    os.makedirs(dst_dir, exist_ok=True)

    entries = []
    for i, name in enumerate(names, start=1):
        src = os.path.join(site_dir, name)
        with Image.open(src) as opened:
            im = ImageOps.exif_transpose(opened).convert("RGB")
        stem = f"{i:02d}"
        # label/alt are descriptive of the file itself; no historical claim.
        label = f"Archive photograph {i} of {len(names)}"
        entries.append({
            "src": _write_variant(im, dst_dir, stem, HERO),
            "thumb": _write_variant(im, dst_dir, stem, THUMB),
            "label": label,
            "width": im.size[0],
            "height": im.size[1],
            "source_file": os.path.relpath(src, ROOT).replace("\\", "/"),
        })

    sites[site_id] = entries
    return len(entries)


def main() -> None:
    os.makedirs(GALLERY_DIR, exist_ok=True)
    sites: dict = {}

    total = 0
    # Indexed monuments: data/raw/<site_id>/
    for site_id in sorted(os.listdir(RAW)):
        src = os.path.join(RAW, site_id)
        if os.path.isdir(src) and site_id != "global":
            total += _collect(src, site_id, sites)

    # Global monuments: data/raw/global/<site_id>/ — keyed the same way the
    # catalogue keys them, so the result view can join on site_id.
    global_root = os.path.join(RAW, "global")
    if os.path.isdir(global_root):
        for site_id in sorted(os.listdir(global_root)):
            src = os.path.join(global_root, site_id)
            if os.path.isdir(src):
                total += _collect(src, site_id, sites)

    manifest = {
        "_comment": (
            "Generated by frontend_new/scripts/prepare_gallery.py from data/raw/. "
            "One entry per real photograph that exists; nothing here is generated."
        ),
        "sites": sites,
    }
    with open(MANIFEST, "w", encoding="utf-8") as fh:
        json.dump(manifest, fh, indent=1)
        fh.write("\n")

    for site_id, entries in sorted(sites.items()):
        print(f"{site_id:52s} {len(entries)} image(s)")
    print(f"\n{total} photographs -> {GALLERY_DIR}")
    print(f"manifest -> {MANIFEST}")


if __name__ == "__main__":
    main()